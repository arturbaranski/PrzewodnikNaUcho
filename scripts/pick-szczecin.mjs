const dist = (a, b) => {
  const p = Math.PI / 180;
  const x = (b.lat - a.lat) * p;
  const y = (b.lng - a.lng) * p * Math.cos(((a.lat + b.lat) / 2) * p);
  return R * Math.hypot(x, y);
};
